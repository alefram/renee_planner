"""The result: the ordered camera poses, saved for the executor and the viewer.

Input: the ordered poses, coverage numbers, experiment metadata, and the
coverage arrays (surface points, views per point, points seen by each pose).
Output: config/trajectories/<experiment>.yaml (what the Behavior Tree reads)
and <experiment>_coverage.npz (for the viewer); `load_*` read them back.
"""
from __future__ import annotations

import os
from dataclasses import asdict, dataclass, field

import numpy as np
import yaml


@dataclass
class CameraPose:
    id: int
    name: str
    section: str
    position: list            # [x, y, z] m, optical frame origin
    orientation: list         # [qx, qy, qz, qw], optical frame (+Z forward, +Y down)
    look_at: list             # [x, y, z] m
    covered: int              # surface points this pose sees
    arc_m: float              # along the lap around the machine
    standoff_m: float
    tilt_deg: float


@dataclass
class Trajectory:
    experiment: str
    mode: str                 # cad | sensor
    frame: str                # frame of every position/orientation (robot_map)
    camera: dict
    coverage: dict
    machine: dict
    poses: list = field(default_factory=list)
    generated: str = ""
    notes: dict = field(default_factory=dict)

    def to_dict(self) -> dict:
        data = asdict(self)
        data["poses"] = [asdict(p) if isinstance(p, CameraPose) else p for p in self.poses]
        return data

    @classmethod
    def from_dict(cls, data: dict) -> "Trajectory":
        fields = {k: data.get(k) for k in cls.__dataclass_fields__ if k in data}
        fields["poses"] = [CameraPose(**pose) for pose in data.get("poses") or []]
        return cls(**fields)


def _plain(value):
    """Output: value with numpy scalars/arrays as plain Python (for YAML)."""
    if isinstance(value, dict):
        return {k: _plain(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [_plain(v) for v in value]
    if isinstance(value, np.ndarray):
        return _plain(value.tolist())
    if isinstance(value, np.generic):
        return value.item()
    if isinstance(value, float):
        return round(value, 6)
    return value


def save_trajectory(trajectory: Trajectory, directory: str, coverage_arrays: dict) -> str:
    """Input: Trajectory, output folder, coverage arrays (points_m, normals, section_ids,
    section_names, view_count, coverable, pose_indptr, pose_indices, lane_xy).
    Output: the YAML path. The npz goes next to it; trajectory.coverage['file'] names it."""
    os.makedirs(directory, exist_ok=True)
    npz_name = f"{trajectory.experiment}_coverage.npz"
    trajectory.coverage["file"] = npz_name
    np.savez_compressed(os.path.join(directory, npz_name), **coverage_arrays)
    path = os.path.join(directory, f"{trajectory.experiment}.yaml")
    header = (f"# Camera poses for {trajectory.experiment} ({trajectory.mode} mode), generated by\n"
              "# renee_trajectory_generation scan_pose_generator_node. Poses are the camera optical\n"
              f"# frame in {trajectory.frame}, in execution order (one forward lap around the machine).\n")
    with open(path, "w") as handle:
        handle.write(header)
        yaml.safe_dump(_plain(trajectory.to_dict()), handle, sort_keys=False, default_flow_style=None, width=120)
    return path


def load_trajectory(path: str) -> Trajectory:
    """Input: a trajectory YAML. Output: Trajectory."""
    with open(path) as handle:
        return Trajectory.from_dict(yaml.safe_load(handle) or {})


def load_coverage(trajectory_path: str, trajectory: Trajectory | None = None) -> dict:
    """Input: the trajectory YAML path (and its Trajectory, if loaded).
    Output: the coverage arrays (dict of numpy arrays), {} if the npz is missing."""
    trajectory = trajectory or load_trajectory(trajectory_path)
    name = (trajectory.coverage or {}).get("file") or f"{trajectory.experiment}_coverage.npz"
    path = os.path.join(os.path.dirname(trajectory_path), name)
    if not os.path.isfile(path):
        return {}
    with np.load(path, allow_pickle=False) as data:
        return {key: data[key] for key in data.files}
